#!/usr/bin/env python3
"""Reproduce Revision 5 PIT tone tables: extract_sounds.py COMIC.EXE src/sound_data.h.
Optional development tool only; running the game does not need Python.
"""
from pathlib import Path
import struct
import sys
from extract_effects import unpack_exepack

def extract(exe):
    image = unpack_exepack(exe)
    if len(image) != 100208 or image[0xfdf0:0xfdf8] != b'lake.tt2':
        raise ValueError('Expected Captain Comic Revision 5')
    tables = [('shot', 0xd46e), ('hit', 0xd47a), ('hurt', 0xd491),
              ('death', 0xd311), ('pickup', 0xd4a1), ('door', 0xd2e9),
              ('teleport', 0xd339), ('arrival', 0xd365), ('life', 0xd4b5), ('theme', 0x84),
              ('panorama', 0xd3ff)]
    output = ['/* Original Revision 5 PIT divisor / BIOS tick pairs. Generated by tools/extract_sounds.py. */']
    for name, address in tables:
        offset = 0x2740 + address
        values = []
        for _ in range(256):
            divisor = struct.unpack_from('<H', image, offset)[0]
            offset += 2
            if not divisor:
                break
            ticks = struct.unpack_from('<H', image, offset)[0]
            offset += 2
            if not 1 <= ticks <= 100:
                raise ValueError('Invalid tone duration')
            values.append((divisor, ticks))
        else:
            raise ValueError('Missing tone terminator')
        output.append('static const Tone tones_%s[] = {\n\t%s\n};' %
                      (name, ', '.join('{%d, %d}' % pair for pair in values)))
    return '\n'.join(output) + '\n'

if __name__ == '__main__':
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    Path(sys.argv[2]).write_text(extract(Path(sys.argv[1]).read_bytes()))
