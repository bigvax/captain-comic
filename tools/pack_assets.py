#!/usr/bin/env python3
"""Build a reproducible runtime archive and an optional read-only C array."""
from io import BytesIO
from pathlib import Path
import sys
import zipfile

ROOT = Path(__file__).resolve().parent.parent


def write_changed(path, content):
    if not path.exists() or path.read_bytes() != content:
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_suffix(path.suffix + '.tmp')
        temporary.write_bytes(content)
        temporary.replace(path)


def pack():
    stream = BytesIO()
    with zipfile.ZipFile(stream, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for path in sorted((ROOT / 'assets').rglob('*')):
            if not path.is_file() or 'enemies' in path.parts or path.suffix == '.ico':
                continue
            info = zipfile.ZipInfo(path.relative_to(ROOT).as_posix(), (1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, path.read_bytes(), compresslevel=9)
    write_changed(ROOT / 'data/assets.pak', stream.getvalue())


def embed():
    data = (ROOT / 'data/assets.pak').read_bytes()
    lines = ['/* Generated by tools/pack_assets.py; do not edit. */',
             'static const unsigned char assets_pak[] = {']
    lines += ['\t' + ', '.join(f'0x{x:02x}' for x in data[i:i + 16]) + ','
              for i in range(0, len(data), 16)]
    lines += ['};', f'static const unsigned int assets_pak_len = {len(data)};']
    write_changed(ROOT / 'src/assets_data.h', ('\n'.join(lines) + '\n').encode())


if __name__ == '__main__':
    if sys.argv[1:] == ['pack']:
        pack()
    elif sys.argv[1:] == ['embed']:
        embed()
    else:
        raise SystemExit('Usage: pack_assets.py pack|embed')
